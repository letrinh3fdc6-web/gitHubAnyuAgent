const {test} = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const {AgentWorkbench} = require('../agent-workbench.cjs')
const {VideoStudio} = require('../video-studio.cjs')
const {CodexTools} = require('../codex-tools.cjs')
const {pathToFileURL} = require('node:url')

test('Pi and App Server tool adapters call the same installed studio in the originating conversation', {timeout: 60000}, async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'anyu-video-tools-'))
  const stage = path.resolve(__dirname, '../../../../outputs/anyu-video-studio-internal/build/win32-x64')
  const skills = {root: path.join(directory, 'skills')}
  await fs.mkdir(path.join(skills.root, 'anyu-video-studio'), {recursive: true})
  await fs.copyFile(path.resolve(__dirname, '../../../../skills/anyu-video-studio/SKILL.md'), path.join(skills.root, 'anyu-video-studio/SKILL.md'))
  const video = new VideoStudio({userData: directory, skills, version: '1.0.82', apiBase: () => 'https://x.ailzd.com', devRoot: stage})
  const wb = new AgentWorkbench({directory: path.join(directory, 'tasks'), getOwner: () => 'local', encrypt: x => x, decrypt: x => x, video: (task, input) => video.dispatch(task, input)})
  await wb.init()
  const task = await wb.begin({sessionId: 'video-tools', cwd: directory, model: 'selected-user-model'}, {runId: 'video-tools-run', input: 'Read templates'}, {lazyCheckpoint: true})
  const context = wb.context(task.sessionId)
  const saved = Object.fromEntries(['ANYU_TASK_PORT', 'ANYU_TASK_TOKEN', 'ANYU_PERMISSION_MODE'].map(key => [key, process.env[key]]))
  Object.assign(process.env, {ANYU_TASK_PORT: String(context.port), ANYU_TASK_TOKEN: context.token, ANYU_PERMISSION_MODE: 'full'})
  t.after(async () => {
    for (const [key, value] of Object.entries(saved)) { if (value === undefined) delete process.env[key]; else process.env[key] = value }
    await video.close(); await wb.close(); await fs.rm(directory, {recursive: true, force: true, maxRetries: 4, retryDelay: 300})
  })
  await video.prepare()
  const extension = await import(pathToFileURL(path.resolve(__dirname, '../pi-workbench-extension.mjs')).href)
  const registered = new Map()
  extension.default({registerTool: tool => registered.set(tool.name, tool), on() {}})
  const piResult = await registered.get('video_studio').execute('pi-catalog', {action: 'catalog', query: 'text-basic'})
  assert.equal(piResult.details.cards[0].id, 'text-basic')
  const tools = await new CodexTools({cwd: directory, agentDir: path.join(directory, 'agent'), ask: async () => true, emit() {}, model: {id: 'test'}}).initialize()
  assert.ok(tools.specs().some(tool => tool.name === 'video_studio'))
  const nativeResult = await tools.perform({tool: 'video_studio', callId: 'native-catalog', arguments: {action: 'catalog', query: 'text-basic'}})
  assert.equal(nativeResult.success, true, JSON.stringify(nativeResult))
  assert.match(nativeResult.contentItems[0].text, /text-basic/)
  const bundle = require('../package.json').build.files
  assert.ok(bundle.includes('video-studio.cjs'))
})
