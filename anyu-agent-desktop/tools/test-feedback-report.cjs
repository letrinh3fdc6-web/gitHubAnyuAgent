const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { reportPrompt, reportAnalysisPrompt, reportPromptWithAnalysis, reportHtml, reportStreamPreview, reportContext } = require('../feedback-report.cjs')

const root = path.join(__dirname, '..', 'skills', 'tmall-public-feedback-analysis')
const stylesheet = fs.readFileSync(path.join(root, 'styles', 'report.css'), 'utf8')
const instruction = fs.readFileSync(path.join(root, 'prompts', 'report.md'), 'utf8')
const generated = fs.readFileSync(path.join(__dirname, 'fixtures', 'feedback-report.html'), 'utf8')
const data = {
  itemId: '42', product: { title: '<孕妇压力袜>' }, collectedAt: '2026-09-29T12:00:00Z',
  reviews: [{ content: '包装完整，质量不错' }], questions: [],
  coverage: { reviews: { platformLabel: '36', platformFolded: 21, limitation: '仅可见 1 条' }, questions: { platformTotal: 0 } }
}
const { prompt, sampled } = reportPrompt(data, '了解用户需求', instruction)
assert.match(prompt, /这个产品有哪些人群在使用/)
assert.match(prompt, /recordCounts.*reviews.*1.*questions.*0/)
assert.equal(sampled.questions, 0)
const natural = reportAnalysisPrompt(data, '了解用户需求')
assert.match(natural.prompt, /像正常对话一样逐段输出简体中文/)
assert.match(natural.prompt, /包装完整，质量不错/)
assert.match(reportPromptWithAnalysis(data, '', instruction, '优先关注包装').prompt, /已展示给用户的分析正文/)
assert.equal(reportStreamPreview(generated.slice(0, generated.indexOf('<main>'))), '')
assert.match(reportStreamPreview(generated.slice(0, generated.indexOf('</section>') + 10)), /执行摘要[\s\S]*包装完整/)
assert.doesNotMatch(reportStreamPreview(generated), /<section|<p|alert/)
const limited = reportContext({ reviews: [{ content: '短评' }, { content: '较长的评论' }], questions: [] }, 175)
assert.equal(JSON.parse(limited.encoded).reviews.length, limited.sampled.reviews)
assert.equal(limited.sampled.reviews, 1)
const html = reportHtml(data, generated, stylesheet)
assert.match(html, /&lt;孕妇压力袜&gt;/)
assert.match(html, /平台标示评价<\/span><strong>36/)
assert.match(html, /平台折叠<\/span><strong>21/)
assert.match(html, /已采问答<\/span><strong>0/)
assert.match(html, /包装完整，质量不错/)
assert.match(html, /模型分析 1 条评价和 0 条问答/)
assert.equal((html.match(/<main>/g) || []).length, 1)
assert.doesNotMatch(html, /alert\('unsafe'\)|color:red|<script/)
assert.throws(() => reportHtml(data, '# Markdown', stylesheet), /完整 HTML/)
assert.throws(() => reportHtml(data, generated.replace('<h2>研究限制</h2>', '<h2>其他</h2>').replace('<h2>使用场景</h2>', '<h2>其他</h2>').replace('<h2>使用目的</h2>', '<h2>其他</h2>'), stylesheet), /缺少必要/)
console.log('feedback report: original prompt, verified coverage, semantic sections and sanitization passed')
