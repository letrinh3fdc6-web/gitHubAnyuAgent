'use strict'

const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const { ResultStorage, hashFile, key } = require('../result-storage.cjs')
const { WorkspaceCheckpoints } = require('../workspace-checkpoints.cjs')
const { ArtifactPreviews } = require('../browser-policy.cjs')

async function fixture(t) {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'anyu-results-')))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  const userData = path.join(root, 'user-data'), install = path.join(root, 'AnyuAgent'), legacy = path.join(install, 'workspace')
  await fs.mkdir(legacy, { recursive: true })
  const fresh = () => new ResultStorage({ userData, legacyRoots: [legacy] })
  return { root, userData, install, legacy, fresh, storage: fresh() }
}

test('default workspace is outside binaries; migration copies every file and survives replacement/restart', async t => {
  const { userData, install, legacy, storage, fresh } = await fixture(t)
  const file = path.join(legacy, '子目录', '作品 #21.svg')
  await fs.mkdir(path.dirname(file)); await fs.writeFile(file, '<svg>original result</svg>')
  assert.equal(await storage.resolveWorkspace(''), path.join(userData, 'workspace'))
  const migrated = await storage.resolveWorkspace(legacy)
  assert.notEqual(migrated, legacy)
  assert.equal(await fs.readFile(file, 'utf8'), '<svg>original result</svg>')
  await fs.rm(install, { recursive: true, force: true })
  const restarted = new ResultStorage({ userData })
  const result = await restarted.resolve(legacy, '子目录/作品 #21.svg')
  assert.equal(await fs.readFile(result, 'utf8'), '<svg>original result</svg>')
  assert.equal(await restarted.resolve('', file), result)
  assert.equal(await restarted.resolveWorkspace(migrated), migrated)
})

test('same filenames from different installation roots stay distinct; custom workspaces remain in place', async t => {
  const { root, legacy, storage } = await fixture(t)
  const other = path.join(root, 'other-install', 'workspace'), custom = path.join(root, 'my-project')
  await fs.mkdir(other, { recursive: true }); await fs.mkdir(custom)
  await fs.writeFile(path.join(legacy, 'result.svg'), 'first')
  await fs.writeFile(path.join(other, 'result.svg'), 'second')
  storage.registerLegacy(other)
  assert.equal(await storage.resolveWorkspace(custom), custom)
  assert.equal(await fs.readFile(await storage.resolve(legacy, 'result.svg'), 'utf8'), 'first')
  assert.equal(await fs.readFile(await storage.resolve(other, 'result.svg'), 'utf8'), 'second')
})

test('temporary results survive deletion, one-day aging and a separate process restart', async t => {
  const { root, userData, storage } = await fixture(t)
  const file = path.join(root, 'temporary.svg')
  await fs.writeFile(file, '<svg>retained forever without TTL</svg>')
  await storage.preserveResult(root, file)
  await storage.flush()
  const records = path.join(userData, 'result-storage', 'records')
  for (const name of await fs.readdir(records)) {
    const target = path.join(records, name), record = JSON.parse(await fs.readFile(target, 'utf8'))
    record.at = '2020-01-01T00:00:00.000Z'; await fs.writeFile(target, JSON.stringify(record))
  }
  await fs.unlink(file)
  const script = "const {ResultStorage}=require(process.env.RESULT_MODULE); const fs=require('node:fs/promises'); new ResultStorage({userData:process.env.RESULT_DATA}).resolve('',process.env.RESULT_ORIGINAL).then(p=>fs.readFile(p,'utf8')).then(s=>process.stdout.write(s)).catch(e=>{console.error(e);process.exitCode=1})"
  const result = spawnSync(process.execPath, ['-e', script], { encoding: 'utf8', windowsHide: true, env: { ...process.env, RESULT_MODULE: path.resolve(__dirname, '../result-storage.cjs'), RESULT_DATA: userData, RESULT_ORIGINAL: file } })
  assert.equal(result.status, 0, result.stderr)
  assert.equal(result.stdout, '<svg>retained forever without TTL</svg>')
})

test('HTML relative CSS and images remain previewable after their temporary project is removed', async t => {
  const { root, storage, fresh } = await fixture(t)
  const project = path.join(root, 'temporary-project'), pages = path.join(project, 'pages'), assets = path.join(project, 'assets')
  await fs.mkdir(pages, { recursive: true }); await fs.mkdir(assets)
  const file = path.join(pages, 'page.html')
  await fs.writeFile(file, '<!doctype html><html><head><link rel="stylesheet" href="../assets/style.css" /></head><body><img src="../assets/photo.png" /></body></html>')
  await fs.writeFile(path.join(assets, 'style.css'), 'body{background:url("texture.png")}')
  await fs.writeFile(path.join(assets, 'photo.png'), 'photo')
  await fs.writeFile(path.join(assets, 'texture.png'), 'texture')
  await storage.preserveResult(project, file)
  await fs.rm(project, { recursive: true, force: true })
  const restarted = fresh(), recovered = await restarted.resolve(project, file)
  const previews = new ArtifactPreviews(), url = previews.open(recovered, await restarted.previewRoot(recovered, project))
  assert.equal(await fs.readFile(previews.resolve(new URL('../assets/photo.png', url).href), 'utf8'), 'photo')
  assert.equal(await fs.readFile(previews.resolve(new URL('../assets/texture.png', url).href), 'utf8'), 'texture')
})

test('completed writes are preserved without opening a preview; separate sessions flush independently', async t => {
  const { root, storage, fresh } = await fixture(t)
  const files = ['one.txt', 'two.txt']
  for (const file of files) await fs.writeFile(path.join(root, file), file)
  files.forEach((file, i) => {
    storage.observe({ sessionId: 'session-' + i, toolCallId: 'same-tool', type: 'tool.started', toolName: 'write', args: { path: file } }, { cwd: root })
    storage.observe({ sessionId: 'session-' + i, toolCallId: 'same-tool', type: 'tool.completed', toolName: 'write', args: {} }, { cwd: root })
  })
  await storage.flush()
  for (const file of files) await fs.unlink(path.join(root, file))
  for (const file of files) assert.equal(await fs.readFile(await fresh().resolve(root, file), 'utf8'), file)
})

test('legacy checkpoint recovery restores exact content plus resources without modifying unrelated files', async t => {
  const { userData, legacy, install, fresh } = await fixture(t)
  await fs.writeFile(path.join(legacy, 'result.svg'), '<svg>checkpoint</svg>')
  await fs.writeFile(path.join(legacy, 'image.png'), 'image')
  const snapshots = new WorkspaceCheckpoints(path.join(userData, 'task-workbench', 'blobs'))
  await snapshots.persist('run-after', await snapshots.capture(legacy))
  await fs.rm(install, { recursive: true, force: true })
  const storage = fresh(), result = await storage.resolve(legacy, 'result.svg')
  assert.equal(await fs.readFile(result, 'utf8'), '<svg>checkpoint</svg>')
  assert.equal(await fs.readFile(path.join(path.dirname(result), 'image.png'), 'utf8'), 'image')
  await assert.rejects(fs.stat(path.join(legacy, 'result.svg')), { code: 'ENOENT' })
  await assert.rejects(storage.resolve(path.dirname(legacy), 'result.svg'), /未找到可验证/)
})

