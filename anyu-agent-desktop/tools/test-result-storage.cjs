test('corrupt archived content is rejected; a missing result is never replaced by an unrelated basename', async t => {
  const { root, storage, fresh } = await fixture(t)
  const file = path.join(root, 'one.svg')
  await fs.writeFile(file, 'correct')
  const hash = await hashFile(file)
  await storage.preserveResult(root, file)
  await fs.unlink(file)
  await fs.writeFile(path.join(storage.directory, 'blobs', hash), 'corrupt')
  await assert.rejects(fresh().resolve(root, file), /校验失败/)
  await assert.rejects(fresh().resolve(path.join(root, 'another'), 'one.svg'), /未找到可验证/)
})

