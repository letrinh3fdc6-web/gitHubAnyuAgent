test('unchanged preview resources are not recopied; edits and deleted copies are preserved again', async t => {
  const { root, storage } = await fixture(t)
  const file = path.join(root, 'large-result.txt')
  await fs.writeFile(file, 'initial')
  const mirror = await storage.preserve(file, root)
  const first = await fs.stat(mirror)
  await storage.preserve(file, root)
  assert.equal((await fs.stat(mirror)).mtimeMs, first.mtimeMs)
  await fs.writeFile(file, 'changed result')
  await storage.preserve(file, root)
  assert.equal(await fs.readFile(mirror, 'utf8'), 'changed result')
  await fs.unlink(mirror)
  await storage.preserve(file, root)
  assert.equal(await fs.readFile(mirror, 'utf8'), 'changed result')
})

test('reopening original links preserves user edits in recovered files and checkpoint resources', async t => {
  const { root, userData, storage, fresh } = await fixture(t)
  const file = path.join(root, 'result.txt')
  await fs.writeFile(file, 'initial'); await storage.preserveResult(root, file)
  await fs.unlink(file)
  const recovered = await storage.resolve(root, file)
  await fs.writeFile(recovered, 'user edit')
  assert.equal(await fs.readFile(await fresh().resolve(root, file), 'utf8'), 'user edit')
  const project = path.join(root, 'checkpoint-source')
  await fs.mkdir(project)
  await fs.writeFile(path.join(project, 'result.html'), '<h1>initial</h1>')
  await fs.writeFile(path.join(project, 'style.css'), 'initial style')
  const checkpoints = new WorkspaceCheckpoints(path.join(userData, 'task-workbench', 'blobs'))
  await checkpoints.persist('after', await checkpoints.capture(project))
  await fs.rm(project, { recursive: true, force: true })
  const html = await storage.resolve(project, 'result.html')
  await fs.writeFile(html, '<h1>user edit</h1>')
  await storage.resolve(project, 'style.css')
  assert.equal(await fs.readFile(html, 'utf8'), '<h1>user edit</h1>')
})

test('concurrent results with identical content create complete atomic archive blobs', async t => {
  const { root, storage, fresh } = await fixture(t)
  const content = Buffer.alloc(1024 * 1024, 65)
  const files = Array.from({ length: 8 }, (_, i) => path.join(root, `same-${i}.bin`))
  await Promise.all(files.map(file => fs.writeFile(file, content)))
  await Promise.all(files.map(file => storage.preserveResult(root, file)))
  await Promise.all(files.map(file => fs.unlink(file)))
  for (const file of files) assert.deepEqual(await fs.readFile(await fresh().resolve(root, file)), content)
})

test('installer backup is outside the deleted install and automatically imported by the next version', { skip: process.platform !== 'win32' }, async t => {
  const { legacy, install, fresh } = await fixture(t)
  await fs.writeFile(path.join(legacy, 'saved.svg'), 'installer preserved')
  const script = path.resolve(__dirname, '../build/preserve-workspace.ps1')
  const result = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', script, '-InstallDirectory', install], { encoding: 'utf8', windowsHide: true, timeout: 30000 })
  assert.equal(result.status, 0, result.stderr + result.stdout)
  assert.equal(await fs.readFile(path.join(legacy, 'saved.svg'), 'utf8'), 'installer preserved')
  await fs.rm(install, { recursive: true, force: true })
  assert.equal(await fs.readFile(await fresh().resolve(legacy, 'saved.svg'), 'utf8'), 'installer preserved')
})

test('installer refuses an unsafe linked workspace and leaves both target and installation intact', { skip: process.platform !== 'win32' }, async t => {
  const { root, legacy, install } = await fixture(t)
  const outside = path.join(root, 'external-data')
  await fs.mkdir(outside); await fs.writeFile(path.join(outside, 'precious.txt'), 'keep')
  await fs.symlink(outside, path.join(legacy, 'linked'), 'junction')
  const result = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', path.resolve(__dirname, '../build/preserve-workspace.ps1'), '-InstallDirectory', install], { encoding: 'utf8', windowsHide: true, timeout: 30000 })
  assert.equal(result.status, 36)
  assert.equal(await fs.readFile(path.join(outside, 'precious.txt'), 'utf8'), 'keep')
  assert.equal((await fs.stat(legacy)).isDirectory(), true)
})
