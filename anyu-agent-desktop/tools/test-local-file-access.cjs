const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { localFilePath, ArtifactPreviews } = require('../browser-policy.cjs')

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'anyu-local-files-'))
  const cwd = path.join(root, 'workspace')
  const outside = path.join(root, 'outside folder')
  fs.mkdirSync(cwd)
  fs.mkdirSync(outside)
  const file = path.join(outside, 'image # 100%.png')
  fs.writeFileSync(file, 'fixture')
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  return { root, cwd, outside, file }
}

test('absolute paths and file URLs work without a workspace; relative paths resolve from it', t => {
  const { cwd, file } = fixture(t)
  assert.equal(localFilePath(cwd, file), file)
  assert.equal(localFilePath('', file), file)
  assert.equal(localFilePath('Z:\\missing-workspace', pathToFileURL(file).href), file)
  assert.equal(localFilePath('', `artifact://${file}`), file)
  assert.equal(localFilePath('', '~'), fs.realpathSync(os.homedir()))
  assert.equal(localFilePath(cwd, path.relative(cwd, file)), file)
  assert.throws(() => localFilePath('', 'relative.png'), /工作目录/)
  assert.throws(() => localFilePath(cwd, 'missing.png'), { code: 'ENOENT' })
})

test('external images have individual preview origins and do not expose siblings', t => {
  const { cwd, outside, file } = fixture(t)
  const next = path.join(outside, 'second.png')
  fs.writeFileSync(next, 'second')
  const previews = new ArtifactPreviews()
  const firstUrl = previews.open(file, cwd)
  const secondUrl = previews.open(next, cwd)
  assert.notEqual(new URL(firstUrl).host, new URL(secondUrl).host)
  assert.equal(previews.resolve(firstUrl), file)
  assert.equal(previews.resolve(secondUrl), next)
  assert.throws(() => previews.resolve(secondUrl, firstUrl), /跨站/)
  assert.throws(() => previews.resolve(firstUrl, 'https://example.com/'), /跨站/)
  assert.throws(() => previews.resolve(new URL('second.png', firstUrl).href), /未被选中/)
  previews.clear()
  assert.throws(() => previews.resolve(firstUrl), /已失效/)
})

test('HTML retains local resources but traversal and linked directory escapes stay blocked', t => {
  const { cwd, outside } = fixture(t)
  const file = path.join(outside, 'page.html')
  const css = path.join(outside, 'page.css')
  fs.writeFileSync(file, '<link rel="stylesheet" href="page.css">')
  fs.writeFileSync(css, 'body{color:red}')
  fs.writeFileSync(path.join(cwd, 'private.txt'), 'private')
  const previews = new ArtifactPreviews()
  const url = previews.open(file, cwd)
  assert.equal(previews.resolve(new URL('page.css', url).href, url), css)
  assert.throws(() => previews.resolve(`leta-preview://${new URL(url).host}/..%2Fworkspace%2Fprivate.txt`))
  fs.symlinkSync(cwd, path.join(outside, 'linked'), process.platform === 'win32' ? 'junction' : 'dir')
  assert.throws(() => previews.resolve(new URL('linked/private.txt', url).href))
  assert.equal(localFilePath('', path.join(outside, 'linked/private.txt')), path.join(cwd, 'private.txt'))
})
