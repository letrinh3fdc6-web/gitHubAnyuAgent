const assert = require('assert')
const fs = require('fs')
const path = require('path')
const root = path.resolve(__dirname, '..')
for (const id of ['tmall-public-feedback-analysis', 'ai-image-analysis']) {
  const file = path.join(root, 'skills', id, 'SKILL.md')
  assert(fs.existsSync(file), `缺少内置技能 ${id}`)
  const source = fs.readFileSync(file, 'utf8')
  assert(source.includes('明确输入'), `${id} 必须要求显式 @ 触发`)
  assert(source.includes('HTML'), `${id} 必须定义 HTML 结果`)
}
const main = fs.readFileSync(path.join(root, 'main.cjs'), 'utf8')
assert(main.includes('WebContentsView'), '主进程没有内置浏览器视图')
assert(main.includes('sanitizeArtifactHtml'), '结果预览没有 HTML 清洗')
assert(main.includes('allowedBrowserUrl'), '浏览器没有 URL 协议校验')
assert(main.includes("const browserExtension = externalProcessPath('pi-browser-extension.mjs')") && main.includes("args.push('--extension', browserExtension)"), 'Pi 没有加载内置浏览器工具')
assert(main.includes('previewResponse'), '工作区相对资源没有受控预览协议')
const renderer = fs.readFileSync(path.join(root, 'renderer', 'app.js'), 'utf8')
assert(renderer.includes("label: `@${businessAlias || name}`"), '@ 技能菜单未接入已安装技能')
assert(renderer.includes('browserOpenArtifact'), '结果文件没有接入内置预览')
assert(renderer.includes('artifactCardsMarkup'), '结果文件没有转换为产物卡')
assert(main.includes('inspectWorkspaceArtifacts'), '产物卡没有在主进程校验真实文件')
console.log('builtin skills and artifact browser: passed')
