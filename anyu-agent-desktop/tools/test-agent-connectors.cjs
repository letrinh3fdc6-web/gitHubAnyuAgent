const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { TaskStorage } = require('../task-storage.cjs')
const { AgentConnectors } = require('../agent-connectors.cjs')

test('official MCP SDK negotiates stdio, discovers tools, gates calls and closes processes', { timeout: 15000 }, async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'anyu-mcp-test-'))
  const store = new TaskStorage(directory)
  await store.load()
  const connectors = new AgentConnectors({ store, encrypt: text => text, decrypt: text => text })
  t.after(async () => { await connectors.close(); await fs.rm(directory, { recursive: true, force: true }) })
  const [config] = await connectors.save({ name: 'Local fixture', transport: 'stdio', command: process.execPath, args: [path.join(__dirname, 'fixtures/workbench-mcp-server.mjs')] })
  const [health] = await connectors.health(config.id)
  assert.equal(health.health, 'ready')
  assert.equal(health.tools[0].name, 'echo')
  await assert.rejects(connectors.call(config.id, 'echo', { text: 'blocked' }), /enabled/)
  await connectors.allow(config.id, ['echo'])
  const result = await connectors.call(config.id, 'echo', { text: 'MCP_CONNECTED' })
  assert.equal(result.content[0].text, 'MCP_CONNECTED')
  await connectors.remove(config.id)
  assert.equal(connectors.clients.size, 0)
})
